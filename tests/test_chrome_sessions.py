# ---------------------------------------------------------------- encoder --
def _cmd(cid, payload):
    return struct.pack("<H", len(payload) + 1) + bytes([cid]) + payload


def _pad(b):
    return b + b"\0" * ((-len(b)) % 4)


def _pstr(s):
    b = s.encode("utf-8")
    return struct.pack("<i", len(b)) + _pad(b)


def _pstr16(s):
    b = s.encode("utf-16-le")
    return struct.pack("<i", len(b) // 2) + _pad(b)


def _pickle(body):
    return struct.pack("<I", len(body)) + body


class Snss:
    """Writes the commands Chromium uses for windows and tabs."""

    def __init__(self, version=3):
        self.out = bytearray(b"SNSS" + struct.pack("<i", version))

    def add(self, cid, payload):
        self.out += _cmd(cid, payload)
        return self

    def window(self, wid, tabs, selected=0, kind=0, bounds=(0, 0, 800, 600, 1)):
        """tabs: [(tab_id, [(url, title), ...], current_nav_index)]"""
        self.add(9, struct.pack("<ii", wid, kind))
        self.add(14, struct.pack("<iiiiii", wid, *bounds))
        for i, (tid, navs, cur) in enumerate(tabs):
            self.add(0, struct.pack("<ii", wid, tid))
            self.add(2, struct.pack("<ii", tid, i))
            for ni, (url, title) in enumerate(navs):
                self.nav(tid, ni, url, title)
            self.add(7, struct.pack("<ii", tid, cur))
        self.add(8, struct.pack("<ii", wid, selected))
        return self

    def nav(self, tid, idx, url, title):
        body = struct.pack("<ii", tid, idx) + _pstr(url) + _pstr16(title) + b"\0" * 8
        return self.add(6, _pickle(body))

    def tab_index(self, tid, idx):
        return self.add(2, struct.pack("<ii", tid, idx))

    def select_tab(self, wid, idx):
        return self.add(8, struct.pack("<ii", wid, idx))

    def close_tab(self, tid):
        return self.add(16, struct.pack("<iiq", tid, 0, 0))

    def close_window(self, wid):
        return self.add(17, struct.pack("<iiq", wid, 0, 0))

    def prune(self, tid, start, count):
        return self.add(24, struct.pack("<iii", tid, start, count))

    def active(self, wid):
        return self.add(20, struct.pack("<i", wid))

    def bytes(self):
        return bytes(self.out)

    def write(self, path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(self.out)
        return path


def tab(tid, *pages, cur=None):
    pages = list(pages)
    return (tid, pages, len(pages) - 1 if cur is None else cur)


def windows_of(snss):
    _v, cmds, _t = m.read_snss_commands(snss.bytes())
    return m.replay_snss(cmds)


def user_data(tmp, profiles, last_used=None, active=None):
    ud = os.path.join(tmp, "chrome")
    for p in profiles:
        os.makedirs(os.path.join(ud, p, "Sessions"), exist_ok=True)
    with open(os.path.join(ud, "Local State"), "w") as f:
        json.dump({"profile": {
            "profiles_order": list(profiles),
            "info_cache": {p: {} for p in profiles},
            "last_used": last_used or profiles[0],
            "last_active_profiles": list(active if active is not None else profiles),
        }}, f)
    return ud


def session_path(ud, prof, stamp=13400000000000000):
    return os.path.join(ud, prof, "Sessions", f"Session_{stamp}")


